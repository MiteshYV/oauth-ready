import type { Assessment } from "./assess";
import { fmtHours, fmtWait } from "./format";
import { EVIDENCE_LABEL, MILESTONE_LABEL, OWNER_LABEL, type Evidence, type Guide, type ReadinessState } from "./types";
import { VOCAB_BY_ID } from "./vocabulary";

const ev = (g: Guide, e?: Evidence) => {
  if (!e) return "";
  const refs = (e.sourceIds ?? []).map((i) => (g.sources[i] ? `[${i + 1}]` : "")).join("");
  return ` _(${EVIDENCE_LABEL[e.level]}${refs ? " " + refs : ""})_`;
};

const statusMark = (s: string) => (s === "done" ? "[x]" : "[ ]");

// Full guide as Markdown for one use case, for a ticket, doc or chat.
export function guideToMarkdown(g: Guide, a: Assessment, url?: string): string {
  const out: string[] = [];
  const uc = a.useCase;
  out.push(`# ${g.name}: OAuth app setup and approval`);
  out.push("");
  out.push(`**Use case:** ${uc.label} (${uc.scopes.join(", ")})`);
  out.push(`**Difficulty:** ${a.difficulty}. Driven by: ${a.drivers.join("; ")}.`);
  out.push(`Last verified ${g.lastVerified}${g.origin === "live" ? " (generated by an agent, not yet reviewed)" : ""}.${url ? ` Live version: ${url}` : ""}`);
  out.push("");
  out.push(g.summary);
  out.push("");
  if (g.composio?.managedAuth === "yes") out.push("> You can ship today on Composio's managed OAuth app. You need your own for your brand on the consent screen, your own scopes or your own rate limits.", "");
  out.push(uc.summary);
  out.push("");
  out.push("## Time and effort");
  const test = g.verdict.milestones.find((m) => m.id === "test");
  if (test) out.push(`- **${MILESTONE_LABEL.test}:** ${test.activeEffort} hands-on, wait ${test.calendarWait}.`);
  if (a.available) {
    out.push(`- **${MILESTONE_LABEL.production} (typical):** ${fmtHours(a.typical.hours)} hands-on, wait ${fmtWait(a.typical.wait, a.typical.waitUnknown)}.`);
    if (a.personalised) out.push(`- **${MILESTONE_LABEL.production} (for us, given what we already have):** ${fmtHours(a.forYou.hours)} hands-on, wait ${fmtWait(a.forYou.wait, a.forYou.waitUnknown)}.`);
  } else {
    out.push(`- Not available: ${uc.notAvailableReason ?? ""}`);
  }
  if (uc.customerApproval.likelihood !== "none") out.push(`- **Customer approval (${uc.customerApproval.likelihood}):** ${uc.customerApproval.detail ?? uc.customerApproval.who ?? ""}`);
  out.push("");
  out.push("## Likely blockers");
  g.verdict.topBlockers.forEach((b) => out.push(`- **${b.title}.** ${b.detail}${ev(g, b.evidence)}`));
  out.push("");
  out.push("## Before you start (test)");
  g.prerequisites.forEach((p) => out.push(`- [ ] ${p.item}${p.detail ? `: ${p.detail}` : ""} (${OWNER_LABEL[p.owner]})`));
  const testSteps = g.steps.filter((s) => s.milestone === "test");
  if (testSteps.length) {
    out.push("");
    out.push(`## Steps: ${MILESTONE_LABEL.test}`);
    testSteps.forEach((s, i) => {
      out.push(`${i + 1}. **${s.title}** (${OWNER_LABEL[s.owner]}${s.estTime ? `, ${s.estTime}` : ""}). ${s.detail}${s.url ? ` ${s.url}` : ""}${ev(g, s.evidence)}`);
      if (s.agentHelp) out.push(`   - Agent help: ${s.agentHelp}`);
    });
  }
  if (a.todos.length) {
    out.push("");
    out.push(`## Before you go live: ${uc.label}`);
    a.todos.forEach((t) => {
      const parts = [OWNER_LABEL[t.owner]];
      if (t.hoursR) parts.push(fmtHours(t.hoursR));
      if (t.waitR) parts.push(`wait ${fmtWait(t.waitR)}`);
      if (t.optional) parts.push("optional");
      out.push(`- ${statusMark(t.state.status)} **${t.label}** (${parts.join(", ")}).${t.detail ? " " + t.detail : ""}${ev(g, t.evidence)}`);
    });
  }
  const listing = g.steps.filter((s) => s.milestone === "listing");
  if (listing.length) {
    out.push("");
    out.push(`## Optional: ${MILESTONE_LABEL.listing}`);
    listing.forEach((s, i) => out.push(`${i + 1}. **${s.title}**. ${s.detail}${ev(g, s.evidence)}`));
  }
  out.push("");
  out.push("## Nuances");
  g.nuances.forEach((n) => out.push(`- **${n.title}.** ${n.detail}${ev(g, n.evidence)}`));
  out.push("");
  out.push("## If you get stuck");
  g.whenStuck.forEach((w) => out.push(`- **${w.symptom}** ${w.fix}${ev(g, w.evidence)}`));
  if (g.openQuestions.length) {
    out.push("");
    out.push("## Not yet verified");
    g.openQuestions.forEach((q) => out.push(`- ${q}`));
  }
  out.push("");
  out.push("## Sources");
  g.sources.forEach((s, i) => out.push(`${i + 1}. [${s.title}](${s.url})`));
  return out.join("\n");
}

// A task brief for a coding agent (Claude Code, Cursor...) covering what an agent can own.
// Values from the company profile are included so the agent can fill forms, not just draft them.
export function agentBrief(g: Guide, a: Assessment, profile: ReadinessState, url?: string): string {
  const open = a.todos.filter((t) => t.state.status !== "done");
  const agentTodos = open.filter((t) => t.owner === "agent" || t.owner === "agent_assist");
  const humanTodos = open.filter((t) => t.owner === "you");
  const testAgent = g.steps.filter((s) => s.milestone === "test" && (s.owner === "agent" || s.owner === "agent_assist"));
  const values = Object.entries(profile.company)
    .filter(([, v]) => v.value)
    .map(([k, v]) => `- ${VOCAB_BY_ID.get(k)?.valueLabel ?? k}: ${v.value}`);
  const out: string[] = [];
  out.push(`You are helping me set up a ${g.name} OAuth app for my AI agent product, used through a Composio custom auth config.`);
  out.push(`Use case: ${a.useCase.label}. Scopes: ${a.useCase.scopes.join(", ")}.`);
  if (url) out.push(`Reference guide: ${url}`);
  out.push("");
  out.push("Do the following and report back with what you produced. Do not create accounts, accept terms, enter credentials or submit anything to the provider; list those as actions for me.");
  if (values.length) {
    out.push("");
    out.push("Use these company details wherever a form or document needs them:");
    out.push(...values);
  }
  out.push("");
  [...testAgent.map((s) => `${s.title}: ${s.agentHelp ?? s.detail}`), ...agentTodos.map((t) => `${t.label}: ${t.agentHelp ?? t.detail ?? ""}`)].forEach((line, i) => out.push(`${i + 1}. ${line}`));
  out.push("");
  out.push(`Steps I will do myself (prepare me for them): ${humanTodos.map((t) => t.label).join("; ") || "none"}.`);
  if (g.composio?.redirectUriNote) out.push(`Redirect URI: ${g.composio.redirectUriNote}`);
  out.push("Flag anything in the guide that looks outdated when you check the provider's current docs.");
  return out.join("\n");
}
