import Link from "next/link";
import { Evidence } from "./Evidence";
import { Interpretation } from "./Interpretation";
import { ProbeList } from "./ProbeList";
import { Tile } from "./Tile";
import type { NoOAuthGuide } from "@/lib/types";

const METHOD = { api_key: "API key", basic: "Username and password (basic auth)", other: "Another method", not_found: "Not identified" };

// The short guide for apps with nothing to register or approve.
export function NoOAuthView({ guide: g }: { guide: NoOAuthGuide }) {
  const found = g.noOAuth.method !== "not_found";
  return (
    <main className="page">
      <Link href="/" className="back">← All guides</Link>
      <div className="detail-head">
        <Tile name={g.name} large />
        <div style={{ flex: 1, minWidth: 0 }}>
          <h1>{g.name}</h1>
          <div className="meta-line">
            <span className="pill"><span className="dot" />{found ? "No OAuth app needed" : "We couldn't identify this app"}</span>
            <span className="label">Verified {g.lastVerified}</span>
            {g.origin === "live" && <span className="pill pill-live">Generated by an agent, not yet reviewed</span>}
          </div>
          <Interpretation i={g.interpretation} />
          <p className="desc">{g.summary}</p>
        </div>
      </div>

      <section className="section">
        <h2>{found ? "How your users connect" : "What we found"}</h2>
        <div className="card card-pad">
          <p><span className="label">{METHOD[g.noOAuth.method]}</span><br />{g.noOAuth.howUsersConnect}</p>
          <div className="row-meta"><Evidence e={g.noOAuth.evidence} sources={g.sources} /></div>
        </div>
        {found && <p className="fine" style={{ marginTop: 8 }}>There is no OAuth app to register and nothing for the provider to approve, so there is no difficulty rating or waiting time.</p>}
      </section>

      {g.nuances.length > 0 && (
        <section className="section">
          <h2>Details that change the plan</h2>
          <div className="list blocker-list">
            {g.nuances.map((n, i) => <div className="row" key={i}><div><div className="row-title">{n.title}</div><p className="row-detail">{n.detail}</p><div className="row-meta"><Evidence e={n.evidence} sources={g.sources} /></div></div></div>)}
          </div>
        </section>
      )}
      {(g.whenStuck?.length ?? 0) > 0 && (
        <section className="section">
          <h2>If you get stuck</h2>
          <div className="list blocker-list">
            {g.whenStuck!.map((w, i) => <div className="row" key={i}><div><div className="row-title">{w.symptom}</div><p className="row-detail">{w.fix}</p><div className="row-meta"><Evidence e={w.evidence} sources={g.sources} /></div></div></div>)}
          </div>
        </section>
      )}
      <ProbeList probes={g.probes} />
      {g.openQuestions.length > 0 && (
        <section className="section">
          <h2>Not yet verified</h2>
          <div className="list blocker-list">{g.openQuestions.map((q, i) => <div className="row" key={i}><p className="row-detail" style={{ marginTop: 0 }}>{q}</p></div>)}</div>
        </section>
      )}
      <section className="section">
        <h2>Sources</h2>
        <div className="card card-pad">
          <ol className="sources">{g.sources.map((s, i) => <li key={i}><a href={s.url} target="_blank" rel="noreferrer">{s.title}</a><span className="src-type">{s.type}{s.accessed ? ` · ${s.accessed}` : ""}</span></li>)}</ol>
        </div>
        <p style={{ marginTop: 12 }}><a className="btn-outline" href={`/api/guides/${g.slug}`} download={`${g.slug}-guide.json`}>Download JSON</a></p>
      </section>
    </main>
  );
}
